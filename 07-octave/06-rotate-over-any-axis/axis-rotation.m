% Скрипт для GNU Octave: Поворот вокруг произвольной оси
% Выполняет расчет итоговой матрицы трансформации 4x4

clear;
clc;

% ==========================================
% ВХОДНЫЕ ДАННЫЕ (Можно менять под свои задачи)
% ==========================================
% Точка P0, через которую проходит ось поворота
P0 = [1, 2, 3];

% Направляющий вектор оси (не обязательно нормированный, скрипт отнормирует сам)
axis_dir = [0, 1, 1];

% Угол поворота в градусах
angle_deg = 45;

% ==========================================
% ШАГ 1: Нормализация вектора оси
% ==========================================
w = axis_dir / norm(axis_dir); % Это наш новый вектор оси Z

% ==========================================
% ШАГ 2: Кросс-продукт (Построение базиса)
% ==========================================
% Выбираем вспомогательный вектор для поиска перпендикуляра.
% Если ось почти совпадает с Y, берем X, иначе берем Y.
if abs(w(2)) > 0.9
    t = [1, 0, 0];
else
    t = [0, 1, 0];
end

% Находим новую ось X через векторное произведение (cross-product)
r = cross(t, w);
u_new = r / norm(r); % Нормируем, получаем единичный вектор оси X

% Находим новую ось Y через второе векторное произведение
v_new = cross(w, u_new); % Наш правый ортонормированный базис готов

% ==========================================
% ШАГ 3: Формирование матриц трансформации
% ==========================================

% 1. Матрица переноса в начало координат T(-P0)
T_minus = eye(4);
T_minus(1:3, 4) = -P0';

% 2. Матрица выравнивания оси с главной осью Z
% Векторы базиса записываются в СТРОКИ
R_align = eye(4);
R_align(1, 1:3) = u_new;
R_align(2, 1:3) = v_new;
R_align(3, 1:3) = w;

% 3. Стандартная матрица поворота вокруг оси Z
theta = deg2rad(angle_deg); % Переводим угол в радианы
R_z = eye(4);
R_z(1,1) = cos(theta);  R_z(1,2) = -sin(theta);
R_z(2,1) = sin(theta);   R_z(2,2) = cos(theta);

% 4. Обратное выравнивание (транспонированная матрица R_align)
R_align_inv = R_align';
R_align_inv(4, 4) = 1; % Исправляем правый нижний угол после транспонирования

% 5. Обратный перенос на исходную точку T(P0)
T_plus = eye(4);
T_plus(1:3, 4) = P0';

% ==========================================
% ШАГ 4: Расчет итоговой матрицы
% ==========================================
% Перемножаем матрицы справа налево (в порядке применения к объекту)
M = T_plus * R_align_inv * R_z * R_align * T_minus;

% Вывод результатов в консоль Octave
disp('--- Результаты расчета ---');
fprintf('Новый базис (X, Y, Z):\n');
disp([u_new; v_new; w]);

disp('Итоговая аффинная матрица трансформации 4x4:');
disp(M);
